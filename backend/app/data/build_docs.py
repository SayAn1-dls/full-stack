"""Render docs/DATA_DICTIONARY.md from the schema constants and data/processed/run_manifest.json.

    python -m app.data.build_docs

The dictionary is generated so its ranges, counts and first-published dates cannot drift from the data;
a test fails if the committed file differs from a fresh render.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

from app.data.clean_demand import REPO_ROOT
from app.data.demand_schema import COLUMN_DOCS, POWER_COLUMNS

GROUPS = [
    ("Demand (NESO transmission metering)", ["nd", "tsd", "england_wales_demand"]),
    ("Embedded (distribution-connected) wind and solar - NESO estimates", [
        "embedded_wind_generation", "embedded_wind_capacity", "embedded_solar_generation", "embedded_solar_capacity"]),
    ("Reserve and storage", ["non_bm_stor", "pump_storage_pumping"]),
    ("Transfers and interconnector flows", [
        "scottish_transfer", "ifa_flow", "ifa2_flow", "britned_flow", "moyle_flow", "east_west_flow",
        "nemo_flow", "nsl_flow", "eleclink_flow", "viking_flow", "greenlink_flow"]),
]
RULE_FLAG = {"nd": "flag_nd_zero", "tsd": "flag_tsd_zero", "england_wales_demand": "flag_england_wales_demand_zero"}
ZERO_PLACEHOLDER_COLUMNS = {"ifa2_flow", "britned_flow", "east_west_flow", "nemo_flow", "nsl_flow", "eleclink_flow",
                            "viking_flow", "greenlink_flow", "embedded_solar_capacity"}


def _day(ts: str | None) -> str:
    return "-" if ts is None else ts[:10]


def _null_policy(column: str, profile: dict, manifest: dict) -> str:
    nulls = profile["null_rows"]
    if column in RULE_FLAG:
        n = manifest["rows_flagged"][RULE_FLAG[column]]
        return (f"Null only where the raw reading was exactly 0 (`{RULE_FLAG[column]}`): {n:,} rows. "
                "Never imputed.") if n else f"No nulls; a raw 0 would be nulled (`{RULE_FLAG[column]}`); 0 rows today."
    if nulls:
        return (f"Null for the {nulls:,} periods before {_day(profile['first_published_utc'])} (file does not publish "
                "the column; reason `column_not_published`). Never 0, never imputed.")
    return "No nulls."


def _notes(column: str, profile: dict) -> str:
    notes = []
    if COLUMN_DOCS[column].get("notes"):
        notes.append(COLUMN_DOCS[column]["notes"])
    first, nonzero = profile["first_published_utc"], profile["first_nonzero_utc"]
    if column == "greenlink_flow":
        notes.append("Constant 0 in every published row: treated as a placeholder, not measured zero flow "
                     "(flag `constant_column`).")
    elif column in ZERO_PLACEHOLDER_COLUMNS and nonzero and first and nonzero[:10] > first[:10]:
        notes.append(f"Published as 0 from {_day(first)} until the first non-zero reading on {_day(nonzero)}; "
                     "earlier zeros are placeholders (nothing in service or estimated yet), not measured values.")
    elif column == "embedded_solar_generation":
        notes.append("0 overnight is legitimate.")
    return " ".join(notes)


def _range(profile: dict) -> str:
    return "-" if profile["min"] is None else f"{profile['min']:,} to {profile['max']:,}"


def render_data_dictionary(manifest: dict) -> str:
    profile = manifest["column_profile"]
    flagged = manifest["rows_flagged"]
    cov = manifest["coverage"]
    lines: list[str] = []
    add = lines.append
    add("# Data dictionary: `demand_clean`")
    add("")
    add("*Generated by `python -m app.data.build_docs` from `data/processed/run_manifest.json` "
        f"(pipeline {manifest['pipeline_version']}). Do not edit by hand.*")
    add("")
    add("## What this dataset is, and is not")
    add("")
    add("- **Is:** NESO (National Energy System Operator, formerly National Grid ESO) *Historic Demand Data* for Great "
        f"Britain, half-hourly, **{cov['first_settlement_date']} to {cov['last_settlement_date']}** "
        f"({manifest['rows_out']:,} settlement periods). Source: the yearly files listed in `docs/DATA_CLEANING_REPORT.md`.")
    add("- **Is not:** Elexon FUELHH actual generation or WINDFOR wind forecasts. `embedded_wind_generation` is NESO's "
        "*model estimate* of distribution-connected wind only, not transmission-metered national wind output. Do not "
        "chart it as forecast or as national wind generation, and do not join it to Elexon data without explicit "
        "timestamp alignment.")
    add(f"- **Coverage:** ends {cov['last_settlement_date']}. Later dates are *out of coverage*, not missing - "
        "this includes all of January 2026.")
    add("")
    add("## Conventions")
    add("")
    add("- **Power unit:** MW, the average over the 30-minute settlement period. All power columns are nullable "
        "`Int64` (parquet `int64`, CSV integers with blanks for null).")
    add("- **Time:** settlement period 1 starts at 00:00 UK local time (Europe/London) on `settlement_date`; each "
        "period is 30 minutes. `period_start_utc = local midnight (as UTC) + (settlement_period - 1) x 30 min`. Days have "
        "46 (spring clock change), 48 or 50 (autumn clock change) periods; this is correct GB behaviour, not an error. "
        "`period_start_utc` is the primary key and is strictly increasing in exact 30-minute steps.")
    add("- **Signs:** interconnector flows - **negative = export out of GB, positive = import into GB**. "
        "`scottish_transfer` - positive = Scotland to England & Wales. Signs are kept as published; nothing is "
        "absolute-valued.")
    add("- **Nulls:** two reasons only - `invalid_zero_reading` (row kept, cell nulled, flagged) and "
        "`column_not_published` (structural; the source file for that year has no such column). See "
        "`data/processed/demand_null_reasons.csv`. No imputation anywhere in this dataset.")
    add("")
    add("## Key and time columns")
    add("")
    add("| Column | Type | Definition | Null policy |")
    add("|---|---|---|---|")
    add("| `period_start_utc` | timestamp (UTC) | Start of the half-hour, UTC. **Primary key.** | never null |")
    add("| `period_end_utc` | timestamp (UTC) | `period_start_utc` + 30 minutes. | never null |")
    add("| `period_start_local` | timestamp (Europe/London, with offset) | Same instant as `period_start_utc` on the UK "
        "wall clock; the offset (`+00:00`/`+01:00`) distinguishes the repeated autumn hour. | never null |")
    add("| `settlement_date` | date | Original business key: the UK local date of the settlement day. | never null |")
    add("| `settlement_period` | int16 | Original business key: 1..46, 1..48 or 1..50. | never null |")
    add("")
    for title, columns in GROUPS:
        add(f"## {title}")
        add("")
        add("| Column | Type | Unit | Definition (NESO) | Observed range (cleaned) | Null policy | First published (UTC) | "
            "First non-zero (UTC) | Notes |")
        add("|---|---|---|---|---|---|---|---|---|")
        for column in columns:
            p = profile[column]
            doc = COLUMN_DOCS[column]
            add(f"| `{column}` | Int64 | {doc['unit']} | {doc['definition']} | {_range(p)} | "
                f"{_null_policy(column, p, manifest)} | {_day(p['first_published_utc'])} | "
                f"{_day(p['first_nonzero_utc'])} | {_notes(column, p)} |")
        add("")
    add("*Observed range* is the min/max of the cleaned data, not a physical limit. *First published* is the first "
        "period the column has a value in the source files.")
    add("")
    add("## Derived and quality columns")
    add("")
    add("| Column | Type | Definition | Rows true |")
    add("|---|---|---|---|")
    add(f"| `is_bank_holiday_ew` | bool | England & Wales bank holiday *observed* on `settlement_date` (substitute days "
        f"included, nominal weekend dates excluded). Recomputed with the `holidays` package; **not** the combined "
        f"file's undocumented `is_holiday`. Scotland/Northern Ireland holidays excluded. | "
        f"{manifest['is_bank_holiday_ew_rows']:,} |")
    flag_defs = [
        ("flag_nd_zero", "`nd` was exactly 0 (invalid; value nulled)."),
        ("flag_tsd_zero", "`tsd` was exactly 0 (invalid; value nulled). Only the 0 readings are nulled, not the whole day."),
        ("flag_england_wales_demand_zero", "`england_wales_demand` was exactly 0 (invalid; value nulled)."),
        ("flag_tsd_below_nd", "`tsd < nd` after invalid values were nulled (TSD normally exceeds ND). Suspect: value kept."),
        ("flag_wind_gen_above_capacity", "`embedded_wind_generation > embedded_wind_capacity`. Capacity is an estimate. "
                                        "Suspect: value kept."),
        ("flag_negative_stor", "`non_bm_stor < 0`. Suspect: value kept."),
        ("flag_constant_column", "Row carries a value in a column that is constant across its entire published "
                                 "history (`greenlink_flow` = 0). Value kept."),
    ]
    for name, text in flag_defs:
        add(f"| `{name}` | bool | {text} | {flagged[name]:,} |")
    add(f"| `quality_flags` | string | `;`-joined tokens of every flag on the row (`tsd_zero`, "
        f"`england_wales_demand_zero`, `nd_zero`, `tsd_below_nd`, `wind_gen_above_capacity`, `negative_stor`, "
        f"`constant_column:<column>`), or `ok`. | {flagged['any_flag']:,} rows are not `ok` |")
    add("| `source_file` | string | Yearly source file the row came from (provenance). | - |")
    add("| `source_row` | int32 | 1-based data-row number within `source_file` (header excluded). | - |")
    add("")
    add("`tsd_below_nd` note: 501 raw rows have `tsd < nd`, but "
        f"{manifest['tsd_below_nd']['raw_rows'] - manifest['tsd_below_nd']['after_invalid_nulling']:,} of them are the "
        "`tsd == 0` readings that were nulled as invalid; only "
        f"{manifest['tsd_below_nd']['after_invalid_nulling']} are flagged as suspect.")
    add("")
    add("## Companion outputs")
    add("")
    add("| File | Contents |")
    add("|---|---|")
    add("| `demand_clean.parquet`, `demand_clean.csv` | This dataset (identical content; CSV uses ISO-8601 timestamps). |")
    add("| `demand_daily_completeness.csv` | One row per day: expected (46/48/50), present, missing, unexpected, invalid, "
        "suspect and flagged periods. |")
    add("| `demand_null_reasons.csv` | Every null by source file and column with its reason and date span. |")
    add("| `run_manifest.json` | Input SHA-256s, row counts in/out, rows flagged per rule, column profile, versions. |")
    add("| `reference_checks.json`, `is_holiday_disagreements.csv` | Combined-file cross-validation, the `noNaN` file "
        "critique, and the `is_holiday` comparison. |")
    add("")
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Render docs/DATA_DICTIONARY.md")
    parser.add_argument("--manifest", type=Path, default=REPO_ROOT / "data" / "processed" / "run_manifest.json")
    parser.add_argument("--out", type=Path, default=REPO_ROOT / "docs" / "DATA_DICTIONARY.md")
    args = parser.parse_args(argv)
    manifest = json.loads(args.manifest.read_text())
    assert set(manifest["column_profile"]) == set(POWER_COLUMNS)
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(render_data_dictionary(manifest))
    print(f"wrote {args.out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
